"""Writes the robot command constants of the app from docs/robot_command_contract.json.

    python tools/gen_command_contract.py           # writes network/RobotCommandContract.kt
    python tools/gen_command_contract.py --check   # exit 1 when the file is not what the contract gives
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONTRACT = ROOT / "docs" / "robot_command_contract.json"
TARGET = ROOT / "app" / "src" / "main" / "java" / "com" / "hydraumc" / "control" / "network" / "RobotCommandContract.kt"


def render(contract: dict) -> str:
    commands = contract["commands"]
    limits = contract["limits"]
    lines = [
        "// =============================================================================",
        "// HYDRA-UMC-ANDROID-CONTROL - network/RobotCommandContract.kt",
        "// Copyright (C) 2026 JuanenRac (Electro Hobby 3D) <electrohobby3d@gmail.com>",
        "// GPL-3.0-or-later - see LICENSE",
        "// =============================================================================",
        "// Generated by tools/gen_command_contract.py from docs/robot_command_contract.json. Do not edit by hand.",
        "package com.hydraumc.control.network",
        "",
        "/** The control commands of POST /api/robot/{id}/command and the limits the server enforces on them. */",
        "object RobotCommandContract {",
        f"    const val PROTOCOL_VERSION = {int(contract['protocolVersion'])}",
        "",
    ]
    for command in commands:
        lines.append(f"    const val {command['constant']} = \"{command['name']}\"")
    lines += [
        "",
        "    val ALL: Set<String> = setOf(" + ", ".join(c["constant"] for c in commands) + ")",
        "",
        "    /** The commands the server orders by number (`seq`). */",
        "    val NUMBERED: Set<String> = setOf(" + ", ".join(c["constant"] for c in commands if c["numbered"]) + ")",
        "",
        "    /** The commands sent over and over while a control is held; they carry no If-Match in the standard mode. */",
        "    val CONTINUOUS: Set<String> = setOf(" + ", ".join(c["constant"] for c in commands if c["continuous"]) + ")",
        "",
        f"    const val SPEED_MIN = {float(limits['speedMin'])}",
        f"    const val SPEED_MAX = {float(limits['speedMax'])}",
        f"    const val JOG_MAX_AMOUNT = {float(limits['jogMaxAmount'])}",
        f"    const val JOG_STEP_MAX = {float(limits['jogStepMax'])}",
        f"    const val OUTPUT_INDEX_MAX = {int(limits['outputIndexMax'])}",
        "}",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    contract = json.loads(CONTRACT.read_text(encoding="utf-8"))
    names = [c["name"] for c in contract["commands"]]
    if len(set(names)) != len(names):
        print("docs/robot_command_contract.json: a command is listed twice")
        return 1
    text = render(contract)
    if "--check" in argv:
        current = TARGET.read_text(encoding="utf-8") if TARGET.is_file() else ""
        if current.replace("\r\n", "\n") != text:
            print("network/RobotCommandContract.kt does not match docs/robot_command_contract.json: run tools/gen_command_contract.py")
            return 1
        return 0
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
